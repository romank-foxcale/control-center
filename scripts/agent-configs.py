#!/usr/bin/env python3
"""Mirror the canonical agent skills into every supported AI tool's directory."""

from __future__ import annotations

import argparse
import filecmp
import json
import shutil
import subprocess
import sys
import threading
from pathlib import Path


# Codex, Cursor and OpenCode read .agents/skills; Claude Code reads only
# .claude/skills. Copies (not symlinks) survive clones on native Windows.
SOURCE = Path(".agents/skills")
TARGETS = (Path(".claude/skills"),)
INSTRUCTION_STUBS = {
    Path("CLAUDE.md"): "@AGENTS.md",
}
# Claude Code hooks that enforce the hard rules (docs/kit/decisions/0013-rule-hooks.md). This script owns
# the "hooks" key of the shared settings; every other key, such as permissions, is left alone.
SETTINGS = Path(".claude/settings.json")


def hook(event: str) -> list[dict[str, object]]:
    return [{"type": "command", "command": f'"$CLAUDE_PROJECT_DIR"/scripts/hook {event}', "timeout": 15}]


HOOKS = {
    "PreToolUse": [
        {"matcher": "Bash|PowerShell", "hooks": hook("pre-bash")},
        {"matcher": "Read|Grep|Glob", "hooks": hook("pre-read")},
        {"matcher": "Edit|MultiEdit|Write", "hooks": hook("pre-edit")},
    ],
    "PostToolUse": [
        {"matcher": "Edit|MultiEdit|Write", "hooks": hook("post-edit")},
        {"matcher": "Read|Grep|Glob", "hooks": hook("post-read")},
    ],
    "Stop": [{"hooks": hook("stop")}],
    "SessionStart": [{"matcher": "startup", "hooks": hook("session-start")}],
}


# Codex reads a trusted project's .codex/hooks.json (docs/kit/decisions/0033-codex-rule-hooks.md). This script owns the
# whole file. Codex runs a command with the session's cwd and loads project hooks only up to the Git root, so the CC
# root is `git rev-parse --show-toplevel` (no absolute path is committed). Every change here, even a timeout, makes
# Codex skip that hook until the user trusts it again with /hooks; `./cc doctor` reports it.
CODEX_HOOKS_FILE = Path(".codex/hooks.json")


def codex_hook(event: str) -> list[dict[str, object]]:
    return [{"type": "command", "command": f'"$(git rev-parse --show-toplevel)/scripts/hook" {event}', "timeout": 15}]


CODEX_HOOKS = {
    "description": "Generated by ./cc agents sync (scripts/agent-configs.py); edit that script, never this file.",
    "hooks": {
        "PreToolUse": [{"matcher": "^(Bash|apply_patch)$", "hooks": codex_hook("codex-pre-tool")}],
        "PostToolUse": [{"matcher": "^apply_patch$", "hooks": codex_hook("codex-post-tool")}],
        "Stop": [{"hooks": codex_hook("stop")}],
        "SessionStart": [{"matcher": "startup", "hooks": codex_hook("session-start")}],
    },
}


def codex_hook_keys(root: Path) -> list[str]:
    """The keys Codex gives the CC's hooks: <hooks.json path>:<event in snake case>:<group>:<handler>."""
    source = (root / CODEX_HOOKS_FILE).resolve()
    keys = []
    for event, groups in CODEX_HOOKS["hooks"].items():
        snake = "".join(f"_{c.lower()}" if c.isupper() else c for c in event).lstrip("_")
        for group, entry in enumerate(groups):
            keys += [f"{source}:{snake}:{group}:{handler}" for handler in range(len(entry["hooks"]))]
    return keys


def codex_trust_problems(root: Path, listed: list[dict[str, object]]) -> list[str]:
    """What keeps Codex from running the CC's hooks, from its hooks/list answer. Codex skips such a hook silently."""
    source = str((root / CODEX_HOOKS_FILE).resolve())
    ours = {str(hook.get("key")): hook for hook in listed if str(hook.get("sourcePath")) == source}
    fix = "open codex in the CC root and run /hooks to trust the CC's hooks"
    if not ours:
        return [f"Codex loads none of the CC's hooks: the CC folder is not trusted in Codex; {fix}"]
    problems = []
    for key in codex_hook_keys(root):
        hook = ours.get(key)
        state = ("not loaded" if hook is None else "disabled" if hook.get("enabled") is False
                 else None if hook.get("trustStatus") == "trusted" else str(hook.get("trustStatus")))
        if state:
            problems.append(f"{key}: {state}; Codex skips it until you {fix}")
    return problems


def codex_hooks_listed(root: Path, timeout: float = 30) -> list[dict[str, object]]:
    """Ask Codex itself which hooks it would run in the CC root (app-server JSON-RPC hooks/list, no model call)."""
    process = subprocess.Popen(["codex", "app-server"], cwd=root, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                               stderr=subprocess.DEVNULL, text=True, start_new_session=True)
    timer = threading.Timer(timeout, process.kill)
    timer.start()
    try:
        def send(message: dict[str, object]) -> None:
            process.stdin.write(json.dumps({"jsonrpc": "2.0", **message}) + "\n")
            process.stdin.flush()

        def answer(identifier: int) -> dict[str, object]:
            for line in process.stdout:
                message = json.loads(line)
                if message.get("id") == identifier:
                    if "error" in message:
                        raise ValueError(f"codex app-server: {message['error']}")
                    return message["result"]
            raise ValueError("codex app-server ended without an answer")

        send({"id": 1, "method": "initialize", "params": {"clientInfo": {"name": "cc-doctor", "version": "1"}}})
        answer(1)
        send({"method": "initialized", "params": {}})
        send({"id": 2, "method": "hooks/list", "params": {"cwds": [str(root)]}})
        return [hook for entry in answer(2).get("data", []) for hook in entry.get("hooks", [])]
    finally:
        timer.cancel()
        process.kill()
        process.wait()


def codex_trust(root: Path) -> int:
    """./cc doctor: a warning, never a failure. Without the codex CLI there is nothing to check."""
    if not shutil.which("codex"):
        print("note: codex is not installed; Codex hooks not checked")
        return 0
    try:
        problems = codex_trust_problems(root, codex_hooks_listed(root))
    except (OSError, ValueError, KeyError) as error:
        print(f"warning: could not ask Codex for its hooks ({error}); in a Codex chat the rule hooks may not run")
        return 0
    if not problems:
        print(f"codex hooks: all {len(codex_hook_keys(root))} trusted")
    for problem in problems:
        print(f"warning: codex hook {problem}")
    return 0


def files_under(root: Path) -> set[Path]:
    if not root.is_dir():
        return set()
    return {path.relative_to(root) for path in root.rglob("*") if path.is_file()}


def drift(root: Path) -> list[str]:
    source = root / SOURCE
    expected = files_under(source)
    if not expected:
        return [f"{SOURCE}: no canonical skills found"]
    problems: list[str] = []
    for target in TARGETS:
        actual = files_under(root / target)
        for relative in sorted(expected - actual):
            problems.append(f"{target / relative}: missing")
        for relative in sorted(actual - expected):
            problems.append(f"{target / relative}: not in {SOURCE}")
        for relative in sorted(expected & actual):
            if not filecmp.cmp(source / relative, root / target / relative, shallow=False):
                problems.append(f"{target / relative}: differs from {SOURCE / relative}")
    for stub, marker in INSTRUCTION_STUBS.items():
        path = root / stub
        if not path.is_file() or marker not in path.read_text(encoding="utf-8"):
            problems.append(f"{stub}: must exist and contain '{marker}'")
    try:
        if json.loads((root / SETTINGS).read_text(encoding="utf-8")).get("hooks") != HOOKS:
            problems.append(f"{SETTINGS}: hooks differ from scripts/agent-configs.py")
    except (OSError, ValueError) as error:
        problems.append(f"{SETTINGS}: {error}")
    try:
        if json.loads((root / CODEX_HOOKS_FILE).read_text(encoding="utf-8")) != CODEX_HOOKS:
            problems.append(f"{CODEX_HOOKS_FILE}: differs from scripts/agent-configs.py")
    except (OSError, ValueError) as error:
        problems.append(f"{CODEX_HOOKS_FILE}: {error}")
    return problems


def sync(root: Path) -> None:
    source = root / SOURCE
    if not files_under(source):
        raise ValueError(f"{SOURCE}: no canonical skills found")
    for target in TARGETS:
        destination = root / target
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(source, destination)
        print(f"synced {SOURCE} -> {target}")
    path = root / SETTINGS
    settings = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
    settings["hooks"] = HOOKS
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"synced rule hooks -> {SETTINGS}")
    codex = root / CODEX_HOOKS_FILE
    text = json.dumps(CODEX_HOOKS, indent=2) + "\n"
    if not codex.is_file() or codex.read_text(encoding="utf-8") != text:
        codex.parent.mkdir(parents=True, exist_ok=True)
        codex.write_text(text, encoding="utf-8", newline="\n")
        print(f"synced rule hooks -> {CODEX_HOOKS_FILE}; trust them again in Codex with /hooks (./cc doctor checks)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    parser.add_argument("command", choices=("sync", "check", "codex-trust"))
    args = parser.parse_args()
    root = args.root.resolve()
    if args.command == "codex-trust":
        return codex_trust(root)
    try:
        if args.command == "sync":
            sync(root)
            return 0
        problems = drift(root)
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if problems:
        print("agent config drift (run ./cc agents sync):", file=sys.stderr)
        for problem in problems:
            print(f"- {problem}", file=sys.stderr)
        return 1
    print(f"agent configs in sync: {SOURCE} -> {', '.join(map(str, TARGETS))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
